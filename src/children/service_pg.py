from src.core.config import settings


class ChildrenService:
    """Child service using PostgreSQL instead of Firestore, S3 for media storage"""
    
    def __init__(self):
        self._storage_service = None
    
    @property
    def storage_service(self):
        """Lazy initialization of S3 storage service"""
        if self._storage_service is None:
            self._storage_service = S3StorageService()
        return self._storage_service
    
    async def _get_user_id_from_firebase_id(self, db: AsyncSession, firebase_user_id: str) -> Optional[int]:
        """Helper to convert firebase_user_id (string) to integer user_id, auto-creating if needed"""
        try:
            # Try to get existing user
            stmt = select(User.user_id).where(User.firebase_user_id == firebase_user_id)
            result = await db.execute(stmt)
            user_id = result.scalar_one_or_none()
            
            if user_id:
                return user_id
            
            # User doesn't exist - auto-create minimal user
            from src.user.service_pg import UserServicePostgreSQL
            user_service = UserServicePostgreSQL()
            user = await user_service.get_or_create_minimal_user(db, firebase_user_id)
            return user.user_id
            
        except Exception as e:
            print(f"❌ Error getting/creating user_id from firebase_user_id: {str(e)}")
            return None
    
    async def create_child(
        self,
        db: AsyncSession,
        user_id: int,  # Integer user_id (FK to user.user_id)
        name: str,
        age: int,
        interests: List[str],
        image_base64: Optional[str] = None,
        avatar_seed: Optional[str] = None,
        avatar_style: str = "avataaars",
        system_prompt: Optional[str] = None
    ) -> ChildSchema:
        """Create a new child profile for a parent"""
        try:
            # Verify user exists
            stmt = select(User).where(User.user_id == user_id)
            result = await db.execute(stmt)
            user = result.scalar_one_or_none()
            if not user:
                raise HTTPException(status_code=404, detail=f"User with user_id={user_id} not found in database")
            
            # Handle image upload if provided
            image_url = None
            if image_base64:
                try:
                    image_data = base64.b64decode(image_base64)
                    # Use user's firebase_user_id for S3 path (will add child_id after creation)
                    image_url = await self.storage_service.upload_user_image(image_data, f"{user.firebase_user_id}/child_temp")
                    print(f"✅ Child profile image uploaded to S3: {image_url}")
                except Exception as e:
                    print(f"⚠️ Failed to upload child profile image: {str(e)}")
            
            # Generate personalized system prompt if not provided
            if not system_prompt:
                system_prompt = self._generate_personalized_prompt(name, age, interests)
            
            # Create child record with INTEGER user_id (child_id will auto-increment)
            child = Child(
                # child_id is auto-generated by database (BIGINT autoincrement)
                user_id=user_id,  # Use integer user_id FK
                name=name,
                age=age,
                interests=interests or [],
                image_url=image_url,
                child_prompt=system_prompt,  # Database field is 'child_prompt' not 'system_prompt'
                is_active=True
            )
            
            db.add(child)
            await db.flush()  # Flush to get the auto-generated child_id
            await db.refresh(child)  # Refresh to get all auto-generated values
            
            # Capture ALL attributes immediately after refresh to avoid lazy loading after commit
            # Note: Database schema only has these fields (no avatar_seed, avatar_style, avatar_url)
            child_id = child.child_id
            child_name = child.name
            child_age = child.age
            child_interests = child.interests
            child_image_url = child.image_url
            child_prompt = child.child_prompt  # Database field name
            child_voice_clone_id = child.voice_clone_id
            child_is_active = child.is_active
            child_created_at = child.created_at.isoformat() if child.created_at else None
            child_updated_at = child.updated_at.isoformat() if child.updated_at else None
            
            print(f"✅ Child created with child_id={child_id}")
            
            # Update parent's children_count and set as default if first child
            stmt = select(User).where(User.user_id == user_id)
            result = await db.execute(stmt)
            user = result.scalar_one_or_none()
            
            if user:
                children_count = user.children_count + 1
                update_data = {
                    'children_count': children_count,
                    'updated_at': datetime.utcnow()
                }
                
                # Set as default if this is the first child
                if children_count == 1 or not user.default_child_id:
                    update_data['default_child_id'] = child_id
                
                stmt = (
                    update(User)
                    .where(User.user_id == user_id)
                    .values(**update_data)
                )
                await db.execute(stmt)
            
            await db.commit()
            
            print(f"✅ Child profile created in PostgreSQL: child_id={child_id} for user_id={user_id}")
            
            return ChildSchema(
                child_id=child_id,
                name=child_name,
                age=child_age,
                interests=child_interests,
                image_url=child_image_url,
                avatar_seed=avatar_seed,  # Return input params (not in DB)
                avatar_style=avatar_style,  # Return input params (not in DB)
                avatar_url=None,  # Not stored in database
                system_prompt=child_prompt,  # Map child_prompt back to system_prompt for API
                voice_clone_id=child_voice_clone_id,
                is_active=child_is_active,
                created_at=child_created_at,
                updated_at=child_updated_at
            )
            
        except Exception as e:
            await db.rollback()
            print(f"❌ Failed to create child profile: {str(e)}")
            raise HTTPException(status_code=500, detail=f"Failed to create child profile: {str(e)}")
    
    async def get_child(
        self,
        db: AsyncSession,
        user_id: str,  # firebase_user_id (string)
        child_id: int
    ) -> Optional[ChildSchema]:
        """Get a specific child profile"""
        try:
            # Convert firebase_user_id to integer user_id
            integer_user_id = await self._get_user_id_from_firebase_id(db, user_id)
            if not integer_user_id:
                return None
            
            stmt = (
                select(Child)
                .where(Child.user_id == integer_user_id)
                .where(Child.child_id == child_id)
                .where(Child.is_active == True)
            )
            
            result = await db.execute(stmt)
            child = result.scalar_one_or_none()
            
            if not child:
                return None
            
            return ChildSchema(
                child_id=child.child_id,
                name=child.name,
                age=child.age,
                interests=child.interests,
                image_url=child.image_url,
                avatar_seed=None,  # Not stored in database
                avatar_style=None,  # Not stored in database
                avatar_url=None,  # Not stored in database
                system_prompt=child.child_prompt,  # Map child_prompt to system_prompt
                voice_clone_id=child.voice_clone_id,
                is_active=child.is_active,
                created_at=child.created_at.isoformat() if child.created_at else None,
                updated_at=child.updated_at.isoformat() if child.updated_at else None
            )
            
        except Exception as e:
            print(f"❌ Error getting child profile: {str(e)}")
            return None
    
    async def get_all_children(
        self,
        db: AsyncSession,
        user_id: str,  # firebase_user_id (string)
        include_inactive: bool = False
    ) -> List[ChildSchema]:
        """Get all children for a parent"""
        try:
            # Convert firebase_user_id to integer user_id
            print(f"🔍 get_all_children: Looking up firebase_user_id={user_id}")
            integer_user_id = await self._get_user_id_from_firebase_id(db, user_id)
            print(f"🔍 get_all_children: Converted to integer user_id={integer_user_id}")
            if not integer_user_id:
                print(f"❌ get_all_children: No user_id found for firebase_user_id={user_id}")
                return []
            
            stmt = (
                select(Child)
                .where(Child.user_id == integer_user_id)
                .order_by(Child.created_at.desc())
            )
            
            if not include_inactive:
                stmt = stmt.where(Child.is_active == True)
            
            print(f"🔍 get_all_children: Executing query for user_id={integer_user_id}, include_inactive={include_inactive}")
            result = await db.execute(stmt)
            children = result.scalars().all()
            print(f"🔍 get_all_children: Found {len(children)} children")
            
            return [
                ChildSchema(
                    child_id=child.child_id,
                    name=child.name,
                    age=child.age,
                    interests=child.interests,
                    image_url=child.image_url,
                    avatar_seed=None,  # Not stored in database
                    avatar_style=None,  # Not stored in database
                    avatar_url=None,  # Not stored in database
                    system_prompt=child.child_prompt,  # Map child_prompt to system_prompt
                    voice_clone_id=child.voice_clone_id,
                    is_active=child.is_active,
                    created_at=child.created_at.isoformat() if child.created_at else None,
                    updated_at=child.updated_at.isoformat() if child.updated_at else None
                )
                for child in children
            ]
            
        except Exception as e:
            print(f"❌ Error getting children: {str(e)}")
            return []
    
    async def update_child(
        self,
        db: AsyncSession,
        user_id: str,
        child_id: int,
        name: Optional[str] = None,
        age: Optional[int] = None,
        interests: Optional[List[str]] = None,
        image_base64: Optional[str] = None,
        avatar_seed: Optional[str] = None,
        avatar_style: Optional[str] = None,
        system_prompt: Optional[str] = None
    ) -> Optional[ChildSchema]:
        """Update a child profile"""
        try:
            # Get existing child
            existing_child = await self.get_child(db, user_id, child_id)
            if not existing_child:
                raise HTTPException(status_code=404, detail="Child profile not found")
            
            # Convert firebase_user_id to integer user_id
            integer_user_id = await self._get_user_id_from_firebase_id(db, user_id)
            if not integer_user_id:
                raise HTTPException(status_code=404, detail="User not found")
            
            # Prepare updates
            update_data = {'updated_at': datetime.utcnow()}
            
            if name is not None:
                update_data['name'] = name
            if age is not None:
                update_data['age'] = age
            if interests is not None:
                update_data['interests'] = interests
            # avatar_seed and avatar_style are not in database schema - ignore them
            if system_prompt is not None:
                update_data['child_prompt'] = system_prompt  # Database field is child_prompt
            
            # Handle image upload
            if image_base64:
                try:
                    image_data = base64.b64decode(image_base64)
                    image_url = await self.storage_service.upload_user_image(image_data, f"{user_id}/{child_id}")
                    update_data['image_url'] = image_url
                    print(f"✅ Child profile image updated on S3: {image_url}")
                except Exception as e:
                    print(f"⚠️ Failed to upload child profile image: {str(e)}")
            
            # Regenerate system prompt if child info changed
            if (name or age or interests) and system_prompt is None:
                final_name = name if name else existing_child.name
                final_age = age if age else existing_child.age
                final_interests = interests if interests else existing_child.interests
                update_data['child_prompt'] = self._generate_personalized_prompt(final_name, final_age, final_interests)
            
            # Update in database
            stmt = (
                update(Child)
                .where(Child.user_id == integer_user_id)
                .where(Child.child_id == child_id)
                .values(**update_data)
            )
            
            await db.execute(stmt)
            await db.commit()
            
            print(f"✅ Child profile updated in PostgreSQL: {child_id}")
            
            # Return updated child
            return await self.get_child(db, user_id, child_id)
            
        except HTTPException:
            raise
        except Exception as e:
            await db.rollback()
            print(f"❌ Failed to update child profile: {str(e)}")
            raise HTTPException(status_code=500, detail=f"Failed to update child profile: {str(e)}")
    
    async def delete_child(
        self,
        db: AsyncSession,
        user_id: str,
        child_id: int
    ) -> bool:
        """Soft delete a child profile"""
        try:
            # Verify child exists
            child = await self.get_child(db, user_id, child_id)
            if not child:
                raise HTTPException(status_code=404, detail="Child profile not found")
            
            # Convert firebase_user_id to integer user_id
            integer_user_id = await self._get_user_id_from_firebase_id(db, user_id)
            if not integer_user_id:
                raise HTTPException(status_code=404, detail="User not found")
            
            # Soft delete
            stmt = (
                update(Child)
                .where(Child.user_id == integer_user_id)
                .where(Child.child_id == child_id)
                .values(is_active=False, updated_at=datetime.utcnow())
            )
            
            await db.execute(stmt)
            
            # Update parent's children_count and default_child_id if needed
            user_stmt = select(User).where(User.user_id == integer_user_id)
            result = await db.execute(user_stmt)
            user = result.scalar_one_or_none()
            
            if user:
                children_count = max(0, user.children_count - 1)
                update_user_data = {
                    'children_count': children_count,
                    'updated_at': datetime.utcnow()
                }
                
                # If deleting the default child, find another active child
                if user.default_child_id == child_id:
                    active_children = await self.get_all_children(db, user_id, include_inactive=False)
                    update_user_data['default_child_id'] = active_children[0].child_id if active_children else None
                
                stmt = (
                    update(User)
                    .where(User.user_id == integer_user_id)
                    .values(**update_user_data)
                )
                await db.execute(stmt)
            
            await db.commit()
            
            print(f"✅ Child profile deleted (soft) in PostgreSQL: {child_id}")
            return True
            
        except HTTPException:
            raise
        except Exception as e:
            await db.rollback()
            print(f"❌ Failed to delete child profile: {str(e)}")
            raise HTTPException(status_code=500, detail=f"Failed to delete child profile: {str(e)}")
    
