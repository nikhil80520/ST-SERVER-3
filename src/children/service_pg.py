    async def get_children_stats(
        self,
        db: AsyncSession,
        user_id: str
    ) -> Dict[str, Any]:
        """
        Get aggregated statistics across all active children for a parent.
        
        Args:
            db: Database session
            user_id: Firebase user ID (string)
            
        Returns:
            Dictionary with aggregated statistics
        """
        try:
            # Get all children
            children = await self.get_all_children(db, user_id, include_inactive=False)
            
            # Aggregate stats
            total_stories = 0
            total_voice_clones = 0
            total_reference_images = 0
            
            for child in children:
                child_stats = await self.get_child_with_stats(db, user_id, child.child_id)
                if child_stats:
                    total_stories += child_stats.story_count or 0
                    total_voice_clones += child_stats.voice_clones_count or 0
                    total_reference_images += child_stats.reference_images_count or 0
            
            stats = {
                'total_children': len(children),
                'total_stories': total_stories,
                'total_voice_clones': total_voice_clones,
                'total_reference_images': total_reference_images
            }
            
            return {"success": True, "stats": stats}
            
        except Exception as e:
            print(f"❌ Error getting children stats: {str(e)}")
            raise HTTPException(status_code=500, detail=f"Failed to get children stats: {str(e)}")
    
    async def get_child_stories(
        self,
        db: AsyncSession,
        user_id: str,
        child_id: int,
        limit: int = 20,
        offset: int = 0
    ) -> Dict[str, Any]:
        """
        Get all stories for a specific child.
        
        Args:
            db: Database session
            user_id: Firebase user ID (string)
            child_id: Child ID (integer)
            limit: Maximum number of stories to return
            offset: Number of stories to skip
            
        Returns:
            Dictionary with child's stories
        """
        try:
            # Verify child belongs to parent
            child = await self.get_child(db, user_id, child_id)
            if not child:
                raise HTTPException(status_code=404, detail="Child profile not found")
            
            # Import story service and query models
            from src.story.service_pg import story_service_pg
            from src.db.models.story import Story
            from src.db.models.user import User
            from sqlalchemy import select, func
            
            # Get total count
            count_stmt = (
                select(func.count(Story.story_id))
                .join(User, Story.user_id == User.user_id)
                .where(User.firebase_user_id == user_id)
                .where(Story.child_id == child_id)
            )
            count_result = await db.execute(count_stmt)
            total_count = count_result.scalar() or 0
            
            # Get stories for this child
            stories = await story_service_pg.get_user_stories(
                db=db,
                firebase_user_id=user_id,
                child_id=child_id,
                limit=limit,
                offset=offset
            )
            
            return {
                "success": True,
                "child_id": child_id,
                "child_name": child.name,
                "stories": stories if stories else [],
                "total_count": total_count,
                "has_more": (offset + len(stories)) < total_count if stories else False
            }
            
        except HTTPException:
            raise
        except Exception as e:
            print(f"❌ Error getting child stories: {str(e)}")
            raise HTTPException(status_code=500, detail=f"Failed to get child stories: {str(e)}")


